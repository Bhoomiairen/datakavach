#include "check.hpp"
#include "datakavach/validators.hpp"

using namespace dk::validate;

TEST(verhoeff_accepts_published_examples) {
    CHECK(verhoeff("999941057058"));  // UIDAI's sample Aadhaar number
    CHECK(verhoeff("234123412346"));
    CHECK(verhoeff("726018159082"));  // generated by data/idgen.py
}

TEST(verhoeff_catches_single_digit_and_swap_errors) {
    CHECK(!verhoeff("999941057059"));  // last digit changed
    CHECK(!verhoeff("999941057508"));  // neighbouring digits swapped
    CHECK(!verhoeff("abc"));
}

TEST(aadhaar_rules) {
    CHECK(aadhaar("726018159082"));
    CHECK(!aadhaar("339099603082"));   // wrong check digit
    CHECK(!aadhaar("126018159082"));   // cannot start with 0 or 1
    CHECK(!aadhaar("72601815908"));    // 11 digits
    CHECK(!aadhaar("222222222222"));   // all the same digit
}

TEST(pan_structure_and_holder_type) {
    CHECK(pan("JNEPR1948V"));
    CHECK(pan("FDSCS3518W"));          // C = company
    CHECK(!pan("JNEXR1948V"));         // X is not a holder type
    CHECK(!pan("JNEPR194V8"));
    CHECK(!pan("jnepr1948v"));         // lower case is normalised by the detector, not here
}

TEST(gstin_checksum) {
    CHECK_EQ(gstin_check_char("27AAPFU0939F1Z"), 'V');  // example GSTIN from GST documentation
    CHECK(gstin("27AAPFU0939F1ZV"));
    CHECK(gstin("05BTGPP8657S8ZD"));
    CHECK(!gstin("27AAPFU0939F1ZX"));   // wrong check character
    CHECK(gstin_structure("27AAPFU0939F1ZX"));
    CHECK(!gstin_structure("40AAPFU0939F1ZV"));  // no state 40
}

TEST(card_networks_and_luhn) {
    CHECK(card("4111111111111111"));   // Visa test number
    CHECK(card("5574911862527606"));   // Mastercard (generated)
    CHECK(!card("4111111111111112"));  // Luhn fails
    CHECK(!card("9111111111111111"));  // no network starts with 9
    CHECK(luhn("79927398713"));
}

TEST(mobile_ifsc_voter_passport) {
    CHECK(mobile10("9876543210"));
    CHECK(!mobile10("5876543210"));    // Indian mobiles start with 6-9
    CHECK(!mobile10("9999999999"));
    CHECK(ifsc("HDFC0049746"));
    CHECK(!ifsc("HDFC1049746"));       // 5th character must be 0
    CHECK(voter_id("VLA7529170"));
    CHECK(passport("G5236672"));
    CHECK(!passport("G0236672"));
    CHECK(!passport("Q5236672"));
}

TEST(email_and_upi) {
    CHECK(email("airenbhoomi@gmail.com"));
    CHECK(!email("priya@okaxis"));     // no TLD: a UPI ID, not an email
    CHECK(known_upi_handle("okaxis"));
    CHECK(known_upi_handle("YBL"));
    CHECK(!known_upi_handle("gmail"));
}
